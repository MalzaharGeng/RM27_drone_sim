#include <px4_arch/io_timer_hw_description.h>

constexpr io_timers_t io_timers[MAX_IO_TIMERS] = {
	initIOTimer(Timer::Timer1, DMA{DMA::Index1}),
	initIOTimer(Timer::Timer3, DMA{DMA::Index1}),
	initIOTimer(Timer::Timer4, DMA{DMA::Index1}),
	initIOTimer(Timer::Timer15),
};

/* MicoAir743v2 AIO: bidirectional DShot fix for the four AIO ESC outputs (TIM1 CH1-4).
 *
 * Reproduces the vendor "bdshot-fixed" build: internal pull-up + reduced slew rate (25 MHz
 * instead of 50 MHz) on both the output and the capture (input) configuration of PE14/PE13/
 * PE11/PE9. The pulled-up, slower edge keeps the DShot telemetry reply (GCR pulse train,
 * ~1.25 us low at DShot300) decodable on the long PCB traces to the 4-in-1 ESC; the DShot bit
 * timing itself is generated by the timer and is unchanged.
 *
 * Verified against MicoAir743-v2_PX4-v1.17.0_bdshot-fixed_*.bin: gpio_out/gpio_in ==
 * 0x0009144E / 0x0009144D / 0x0009144B / 0x00091449 (official 1.17.0 uses 0x0008184E..49).
 */
static constexpr timer_io_channels_t motorOutput(timer_io_channels_t channel)
{
	channel.gpio_out = (channel.gpio_out & ~GPIO_SPEED_MASK) | GPIO_SPEED_25MHz | GPIO_PULLUP;
	channel.gpio_in = (channel.gpio_in & ~GPIO_SPEED_MASK) | GPIO_SPEED_25MHz | GPIO_PULLUP;
	return channel;
}

constexpr timer_io_channels_t timer_io_channels[MAX_TIMER_IO_CHANNELS] = {
	motorOutput(initIOTimerChannel(io_timers, {Timer::Timer1, Timer::Channel4}, {GPIO::PortE, GPIO::Pin14})),
	motorOutput(initIOTimerChannel(io_timers, {Timer::Timer1, Timer::Channel3}, {GPIO::PortE, GPIO::Pin13})),
	motorOutput(initIOTimerChannel(io_timers, {Timer::Timer1, Timer::Channel2}, {GPIO::PortE, GPIO::Pin11})),
	motorOutput(initIOTimerChannel(io_timers, {Timer::Timer1, Timer::Channel1}, {GPIO::PortE, GPIO::Pin9})),
	initIOTimerChannel(io_timers, {Timer::Timer3, Timer::Channel4}, {GPIO::PortB, GPIO::Pin1}),
	initIOTimerChannel(io_timers, {Timer::Timer3, Timer::Channel3}, {GPIO::PortB, GPIO::Pin0}),
	initIOTimerChannel(io_timers, {Timer::Timer4, Timer::Channel1}, {GPIO::PortD, GPIO::Pin12}),
	initIOTimerChannel(io_timers, {Timer::Timer4, Timer::Channel2}, {GPIO::PortD, GPIO::Pin13}),
	initIOTimerChannel(io_timers, {Timer::Timer15, Timer::Channel1}, {GPIO::PortE, GPIO::Pin5}),
	initIOTimerChannel(io_timers, {Timer::Timer15, Timer::Channel2}, {GPIO::PortE, GPIO::Pin6}),
};

constexpr io_timers_channel_mapping_t io_timers_channel_mapping =
	initIOTimerChannelMapping(io_timers, timer_io_channels);
